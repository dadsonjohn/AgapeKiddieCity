-- 2. Guardian phone rule + duplicate-pupil protection
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'pupils_guardian_phone_10_digits'
  ) then
    alter table public.pupils
      add constraint pupils_guardian_phone_10_digits
      check (guardian_phone ~ '^[0-9]{10}$');
  end if;
end $$;

create index if not exists pupils_name_idx on public.pupils (lower(btrim(full_name)));

create unique index if not exists pupils_unique_name_phone_idx
  on public.pupils (lower(btrim(full_name)), guardian_phone);

-- Existing duplicates are left untouched, but no new duplicate name can be
-- added. This catches the same child entered twice with a different phone,
-- guardian, or class.
create or replace function public.prevent_duplicate_pupil_name()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'UPDATE'
     and lower(btrim(new.full_name)) = lower(btrim(old.full_name)) then
    return new;
  end if;

  if exists (
    select 1
    from public.pupils
    where id is distinct from new.id
      and lower(btrim(full_name)) = lower(btrim(new.full_name))
  ) then
    raise exception 'A pupil named "%" already exists.', new.full_name
      using errcode = '23505';
  end if;

  return new;
end;
$$;

drop trigger if exists pupils_prevent_duplicate_name on public.pupils;
create trigger pupils_prevent_duplicate_name
  before insert or update of full_name on public.pupils
  for each row execute function public.prevent_duplicate_pupil_name();

-- ---------------------------------------------------------------------------
-- 3. Saved receipts
-- ---------------------------------------------------------------------------
create sequence if not exists public.receipts_number_seq;

create table if not exists public.receipts (
  id bigint generated by default as identity primary key,
  receipt_number text unique not null default (
    'AKC-' || to_char(now(), 'YYYYMMDD') || '-' ||
    lpad(nextval('public.receipts_number_seq')::text, 4, '0')
  ),
  payment_id bigint references public.payments(id) on delete set null,
  invoice_id bigint references public.fee_invoices(id) on delete set null,
  pupil_id bigint references public.pupils(id) on delete set null,
  pupil_name text not null,
  pupil_class text,
  term text,
  academic_year text,
  description text,
  amount_paid numeric(12, 2) not null default 0,
  amount_billed numeric(12, 2) not null default 0,
  total_paid numeric(12, 2) not null default 0,
  balance_after numeric(12, 2) not null default 0,
  payment_type text not null default 'Partial',
  note text,
  issued_by text,
  paid_on timestamptz not null default now(),
  created_at timestamptz not null default now()
);

alter table public.receipts alter column receipt_number set default (
  'AKC-' || to_char(now(), 'YYYYMMDD') || '-' ||
  lpad(nextval('public.receipts_number_seq')::text, 4, '0')
);

create index if not exists receipts_pupil_idx on public.receipts (pupil_id);
create index if not exists receipts_paid_on_idx on public.receipts (paid_on desc);

-- Backfill receipts for payments recorded before receipts existed.
insert into public.receipts (
  payment_id, invoice_id, pupil_id, pupil_name, pupil_class, term, academic_year,
  description, amount_paid, amount_billed, total_paid, balance_after,
  payment_type, note, issued_by, paid_on
)
select
  p.id,
  i.id,
  i.pupil_id,
  pu.full_name,
  coalesce(pu.class_level, pu.section),
  i.term,
  i.academic_year,
  i.description,
  p.amount_paid,
  i.amount_billed,
  sum(p.amount_paid) over w,
  greatest(i.amount_billed - sum(p.amount_paid) over w, 0),
  case when sum(p.amount_paid) over w >= i.amount_billed then 'Full' else 'Partial' end,
  p.note,
  'Backfill',
  p.payment_date
from public.payments p
join public.fee_invoices i on i.id = p.invoice_id
join public.pupils pu on pu.id = i.pupil_id
where not exists (
  select 1 from public.receipts r where r.payment_id = p.id
)
window w as (
  partition by p.invoice_id
  order by p.payment_date, p.id
  rows between unbounded preceding and current row
);

