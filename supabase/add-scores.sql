alter table public.pupils add column if not exists gender text;

insert into public.sections (name)
values ('Crèche'), ('Nursery'), ('Kindergarten'), ('Primary')
on conflict (name) do nothing;

-- ---------------------------------------------------------------------------
-- Subjects (e.g. Mathematics, English). A class is given a list of subjects
-- through class_subjects, because each class can study a different set.
-- ---------------------------------------------------------------------------
create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists subjects_name_unique_idx
  on public.subjects (lower(btrim(name)));

create table if not exists public.class_subjects (
  id bigint generated by default as identity primary key,
  class_level text not null,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (class_level, subject_id)
);

-- Assessment components are set per term, because weights can change from
-- one term to another. The weights must add up to 100.
create table if not exists public.assessment_components (
  id bigint generated by default as identity primary key,
  term text not null,
  academic_year text not null,
  name text not null,
  weight numeric(5, 2) not null default 0 check (weight >= 0 and weight <= 100),
  is_attendance boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create unique index if not exists assessment_components_term_name_idx
  on public.assessment_components (term, academic_year, lower(btrim(name)));

-- Optional term dates. They are used to decide which attendance records
-- count towards the attendance component.
create table if not exists public.grading_periods (
  id bigint generated by default as identity primary key,
  term text not null,
  academic_year text not null,
  start_date date,
  end_date date,
  created_at timestamptz not null default now(),
  unique (term, academic_year)
);

-- School-wide grading scale (A-F by default). min_score is the lowest score
-- that earns the grade.
create table if not exists public.grade_scales (
  id bigint generated by default as identity primary key,
  grade text not null,
  min_score numeric(5, 2) not null default 0 check (min_score >= 0 and min_score <= 100),
  remark text,
  sort_order integer not null default 0,
  unique (grade)
);

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  pupil_id bigint not null references public.pupils(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  component_id bigint not null references public.assessment_components(id) on delete cascade,
  term text not null,
  academic_year text not null,
  score numeric(5, 2) not null default 0 check (score >= 0),
  entered_by text,
  updated_at timestamptz not null default now(),
  unique (pupil_id, subject_id, component_id, term, academic_year)
);

-- A saved report card is a frozen snapshot, like a receipt. It stays readable
-- even if scores, subjects, or the pupil are later changed or deleted.
create sequence if not exists public.report_cards_number_seq;

create table if not exists public.report_cards (
  id bigint generated by default as identity primary key,
  report_number text unique not null default (
    'AKC-RPT-' || to_char(now(), 'YYYYMMDD') || '-' ||
    lpad(nextval('public.report_cards_number_seq')::text, 4, '0')
  ),
  pupil_id bigint references public.pupils(id) on delete set null,
  pupil_name text not null,
  pupil_class text,
  section text,
  term text not null,
  academic_year text not null,
  subject_count integer not null default 0,
  total_score numeric(7, 2) not null default 0,
  average_score numeric(5, 2) not null default 0,
  overall_grade text,
  attendance_present integer not null default 0,
  attendance_marked integer not null default 0,
  attendance_percent numeric(5, 2) not null default 0,
  snapshot jsonb not null default '{}'::jsonb,
  issued_by text,
  generated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists class_subjects_class_idx on public.class_subjects (class_level);
create index if not exists scores_pupil_idx on public.scores (pupil_id);
create index if not exists scores_subject_idx on public.scores (subject_id);
create index if not exists scores_term_idx on public.scores (term, academic_year);
create unique index if not exists report_cards_pupil_term_idx
  on public.report_cards (pupil_id, term, academic_year);
create index if not exists report_cards_term_idx on public.report_cards (term, academic_year);

-- RLS + service-role access (the Express server uses the secret key).
alter table public.subjects enable row level security;
alter table public.class_subjects enable row level security;
alter table public.assessment_components enable row level security;
alter table public.grading_periods enable row level security;
alter table public.grade_scales enable row level security;
alter table public.scores enable row level security;
alter table public.report_cards enable row level security;

grant all on public.subjects, public.class_subjects, public.assessment_components,
  public.grading_periods, public.grade_scales, public.scores, public.report_cards
  to service_role;
grant usage, select on all sequences in schema public to service_role;

