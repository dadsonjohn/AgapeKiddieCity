create table if not exists public.sections (
  id bigint generated by default as identity primary key,
  name text unique not null,
  created_at timestamptz not null default now()
);

create table if not exists public.pupils (
  id bigint generated by default as identity primary key,
  full_name text not null,
  section text not null,
  class_level text,
  guardian_name text not null,
  guardian_phone text not null,
  enrollment_status text not null default 'Active',
  created_at timestamptz not null default now()
);

create table if not exists public.fee_invoices (
  id bigint generated by default as identity primary key,
  pupil_id bigint not null references public.pupils(id) on delete cascade,
  term text not null,
  academic_year text not null,
  description text,
  amount_billed numeric(12, 2) not null default 0,
  amount_paid numeric(12, 2) not null default 0,
  status text not null default 'Unpaid',
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.fee_invoices(id) on delete cascade,
  amount_paid numeric(12, 2) not null default 0,
  payment_date timestamptz not null default now(),
  note text
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  pupil_id bigint not null references public.pupils(id) on delete cascade,
  attendance_date date not null,
  status text not null default 'Present',
  created_at timestamptz not null default now(),
  unique (pupil_id, attendance_date)
);

create index if not exists pupils_section_idx on public.pupils (section);
create index if not exists pupils_class_level_idx on public.pupils (class_level);

-- Guardian phone must be exactly 10 digits, and a pupil cannot be entered
-- twice with the same name + guardian phone. Re-run this file in the Supabase
-- SQL Editor once to apply these rules to an existing database.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'pupils_guardian_phone_10_digits'
  ) then
    alter table public.pupils
      add constraint pupils_guardian_phone_10_digits
      check (guardian_phone ~ '^[0-9]{10}$');
  end if;
end $$;

create unique index if not exists pupils_unique_name_phone_idx
  on public.pupils (lower(btrim(full_name)), guardian_phone);

create index if not exists fee_invoices_pupil_idx on public.fee_invoices (pupil_id);
create index if not exists fee_invoices_term_idx on public.fee_invoices (term, academic_year);
create index if not exists payments_invoice_idx on public.payments (invoice_id);
create index if not exists attendance_date_idx on public.attendance (attendance_date);
create index if not exists attendance_pupil_idx on public.attendance (pupil_id);

-- This app talks to Supabase only from the Express server using the secret key.
-- RLS is on with no public policies, so publishable/anon clients cannot read or write.
alter table public.sections enable row level security;
alter table public.pupils enable row level security;
alter table public.fee_invoices enable row level security;
alter table public.payments enable row level security;
alter table public.attendance enable row level security;

-- The Express server connects with the secret key (service role), which bypasses RLS.
grant all on public.sections, public.pupils, public.fee_invoices, public.payments, public.attendance
  to service_role;
grant usage, select on all sequences in schema public to service_role;

insert into public.sections (name)
values ('Crèche'), ('Kindergarten'), ('Primary')
on conflict (name) do nothing;

-- Ask PostgREST to refresh its schema cache immediately after creating tables.
notify pgrst, 'reload schema';
