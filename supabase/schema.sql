-- Guardian phone must be exactly 10 digits, and a pupil cannot be entered
-- twice with the same name + guardian phone.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'pupils_guardian_phone_10_digits'
  ) then
    alter table public.pupils
      add constraint pupils_guardian_phone_10_digits
      check (guardian_phone ~ '^[0-9]{10}$');
  end if;
end $$;

create unique index if not exists pupils_unique_name_phone_idx
  on public.pupils (lower(btrim(full_name)), guardian_phone);

-- A pupil name must be unique across the school. This catches the same child
-- being entered twice with a different phone, guardian, or class. Existing
-- duplicates are left untouched, but no new duplicate name can be added.
create or replace function public.prevent_duplicate_pupil_name()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'UPDATE'
     and lower(btrim(new.full_name)) = lower(btrim(old.full_name)) then
    return new;
  end if;

  if exists (
    select 1
    from public.pupils
    where id is distinct from new.id
      and lower(btrim(full_name)) = lower(btrim(new.full_name))
  ) then
    raise exception 'A pupil named "%" already exists.', new.full_name
      using errcode = '23505';
  end if;

  return new;
end;
$$;

drop trigger if exists pupils_prevent_duplicate_name on public.pupils;
create trigger pupils_prevent_duplicate_name
  before insert or update of full_name on public.pupils
  for each row execute function public.prevent_duplicate_pupil_name();

-- Backfill receipts for payments recorded before receipts existed. Running
-- this again only fills gaps, so it is safe to re-run.
insert into public.receipts (
  payment_id, invoice_id, pupil_id, pupil_name, pupil_class, term, academic_year,
  description, amount_paid, amount_billed, total_paid, balance_after,
  payment_type, note, issued_by, paid_on
)
select
  p.id,
  i.id,
  i.pupil_id,
  pu.full_name,
  coalesce(pu.class_level, pu.section),
  i.term,
  i.academic_year,
  i.description,
  p.amount_paid,
  i.amount_billed,
  sum(p.amount_paid) over w,
  greatest(i.amount_billed - sum(p.amount_paid) over w, 0),
  case when sum(p.amount_paid) over w >= i.amount_billed then 'Full' else 'Partial' end,
  p.note,
  'Backfill',
  p.payment_date
from public.payments p
join public.fee_invoices i on i.id = p.invoice_id
join public.pupils pu on pu.id = i.pupil_id
where not exists (
  select 1 from public.receipts r where r.payment_id = p.id
)
window w as (
  partition by p.invoice_id
  order by p.payment_date, p.id
  rows between unbounded preceding and current row
);

-- This app talks to Supabase only from the Express server using the secret key.
-- RLS is on with no public policies, so publishable/anon clients cannot read or write.
alter table public.sections enable row level security;
alter table public.pupils enable row level security;
alter table public.fee_invoices enable row level security;
alter table public.payments enable row level security;
alter table public.receipts enable row level security;
alter table public.pupil_delete_requests enable row level security;
alter table public.attendance enable row level security;

-- The Express server connects with the secret key (service role), which bypasses RLS.
grant all on public.sections, public.pupils, public.fee_invoices, public.payments,
  public.receipts, public.pupil_delete_requests, public.attendance
  to service_role;
grant usage, select on all sequences in schema public to service_role;

