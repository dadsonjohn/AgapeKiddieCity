create table if not exists public.sections (
  id bigint generated by default as identity primary key,
  name text unique not null,
  created_at timestamptz not null default now()
);

create table if not exists public.pupils (
  id bigint generated by default as identity primary key,
  full_name text not null,
  section text not null,
  class_level text,
  guardian_name text not null,
  guardian_phone text not null,
  date_of_birth date,
  enrollment_status text not null default 'Active',
  created_at timestamptz not null default now()
);

-- Existing databases created before birthdays were added.
alter table public.pupils add column if not exists date_of_birth date;

create table if not exists public.fee_invoices (
  id bigint generated by default as identity primary key,
  pupil_id bigint not null references public.pupils(id) on delete cascade,
  term text not null,
  academic_year text not null,
  description text,
  amount_billed numeric(12, 2) not null default 0,
  amount_paid numeric(12, 2) not null default 0,
  status text not null default 'Unpaid',
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.fee_invoices(id) on delete cascade,
  amount_paid numeric(12, 2) not null default 0,
  payment_date timestamptz not null default now(),
  note text
);

-- A saved receipt is created for every payment. The pupil and invoice details
-- are snapshotted so a receipt stays readable even if the invoice is deleted.
create sequence if not exists public.receipts_number_seq;

create table if not exists public.receipts (
  id bigint generated by default as identity primary key,
  receipt_number text unique not null default (
    'AKC-' || to_char(now(), 'YYYYMMDD') || '-' ||
    lpad(nextval('public.receipts_number_seq')::text, 4, '0')
  ),
  payment_id bigint references public.payments(id) on delete set null,
  invoice_id bigint references public.fee_invoices(id) on delete set null,
  pupil_id bigint references public.pupils(id) on delete set null,
  pupil_name text not null,
  pupil_class text,
  term text,
  academic_year text,
  description text,
  amount_paid numeric(12, 2) not null default 0,
  amount_billed numeric(12, 2) not null default 0,
  total_paid numeric(12, 2) not null default 0,
  balance_after numeric(12, 2) not null default 0,
  payment_type text not null default 'Partial',
  note text,
  issued_by text,
  paid_on timestamptz not null default now(),
  created_at timestamptz not null default now()
);

alter table public.receipts alter column receipt_number set default (
  'AKC-' || to_char(now(), 'YYYYMMDD') || '-' ||
  lpad(nextval('public.receipts_number_seq')::text, 4, '0')
);

-- Teachers request a deletion; an administrator approves or rejects it.
create table if not exists public.pupil_delete_requests (
  id bigint generated by default as identity primary key,
  pupil_id bigint references public.pupils(id) on delete set null,
  pupil_name text not null,
  pupil_class text,
  requested_by_id uuid,
  requested_by_name text,
  requested_by_email text,
  reason text,
  status text not null default 'Pending',
  reviewed_by_name text,
  reviewed_by_email text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  pupil_id bigint not null references public.pupils(id) on delete cascade,
  attendance_date date not null,
  status text not null default 'Present',
  created_at timestamptz not null default now(),
  unique (pupil_id, attendance_date)
);

